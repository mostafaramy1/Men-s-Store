const navLinks = document.querySelectorAll(".nav_middle ul li");

navLinks.forEach((link) => {
    link.addEventListener("click", (e) => {
        // 1. تفعيل كلاس active_nav_links على العنصر المباشر وإزالته من الباقي
        navLinks.forEach((l) => l.classList.remove("active_nav_links"));
        e.currentTarget.classList.add("active_nav_links");

        const selectedCategory = e.target.getAttribute("data-category");

        // إذا كان الزر هو "أحدث الصيحات" (trending)
        if (selectedCategory === "trending") {
            // التمرير السلس إلى قسم المنتجات بدون فلترة
            document.querySelector(".product_section").scrollIntoView({ behavior: "smooth" });
            return; // الخروج من الدالة حتى لا يتم تنفيذ الفلترة
        }

        // باقي الأقسام تقوم بالفلترة كالمعتاد
        if (selectedCategory === "all") {
            renderProducts(products);
        } else {
            const filteredProducts = products.filter(
                (item) => item.category === selectedCategory
            );
            renderProducts(filteredProducts);
        }

        // تحديث الزر النشط في قسم الفلاتر
        filterBtns.forEach((btn) => {
            if (btn.getAttribute("data-category") === selectedCategory) {
                btn.classList.add("active_filter");
            } else {
                btn.classList.remove("active_filter");
            }
        });

        // التمرير لقسم المنتجات
        document.querySelector(".product_section").scrollIntoView({ behavior: "smooth" });
    });
});


