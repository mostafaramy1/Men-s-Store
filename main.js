// دالة إغلاق القائمة
function closeMobileMenu() {
  mobileMenu.classList.remove("open");
  mobileOverlay.classList.remove("active");
}

if (menuBtn) menuBtn.addEventListener("click", openMobileMenu);
if (closeMenuBtn) closeMenuBtn.addEventListener("click", closeMobileMenu);
if (mobileOverlay) mobileOverlay.addEventListener("click", closeMobileMenu);

// تشغيل الفلترة والتنقل من داخل القائمة الجانبية
mobileNavLinks.forEach((link) => {
  link.addEventListener("click", (e) => {
    const selectedCategory = e.target.getAttribute("data-category");

    // 1. إغلاق القائمة بعد الضغط
    closeMobileMenu();

    // 2. إذا كان الزر "أحدث الصيحات"
    if (selectedCategory === "trending") {
      document.querySelector(".product_section").scrollIntoView({ behavior: "smooth" });
      return;
    }

    // 3. تطبيق الفلترة
    if (selectedCategory === "all") {
      renderProducts(products);
    } else {
      const filteredProducts = products.filter((item) => item.category === selectedCategory);
      renderProducts(filteredProducts);
    }

    // 4. مزامنة الأزرار الأساسية أسفل الهيرو
    filterBtns.forEach((btn) => {
      if (btn.getAttribute("data-category") === selectedCategory) {
        btn.classList.add("active_filter");
      } else {
        btn.classList.remove("active_filter");
      }
    });

    // 5. نزول شاشة الموبايل لقسم المنتجات
    document.querySelector(".product_section").scrollIntoView({ behavior: "smooth" });
  });
});