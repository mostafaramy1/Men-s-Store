const modalDesc = document.getElementById('modal-desc');
const modalPrice = document.getElementById('modal-price');

// 1. فتح الـ Modal عند الضغط على الكارد
productsContainer.addEventListener('click', (e) => {
  // التأكد أن الضغطة لم تكن على زرار القلب أو زِر الإضافة السريع
  if (e.target.classList.contains('fa-heart') || e.target.classList.contains('fa-plus')) {
    return;
  }

  // البحث عن أقرب كارت تم الضغط عليه
  const card = e.target.closest('.card');
  if (!card) return;

  const productId = card.getAttribute('data-id');
  const product = products.find(p => p.id == productId);

  if (product) {
    // تعبئة بيانات المنتج داخل الـ Modal
    modalImg.src = product.img;
    modalTitle.textContent = product.disc;
    modalCategory.textContent = `القسم: ${product.category}`;
    modalRate.textContent = `(${product.num_rate})`;
    modalDesc.textContent = product.sm_disc;
    modalPrice.textContent = `${product.price} ج.م`;

    // إظهار الـ Modal
    modal.classList.add('active');
  }
});

// 2. إغلاق الـ Modal عند الضغط على زر X
closeModalBtn.addEventListener('click', () => {
  modal.classList.remove('active');
});

// 3. إغلاق الـ Modal عند الضغط في أي مكان خارجه
window.addEventListener('click', (e) => {
  if (e.target === modal) {
    modal.classList.remove('active');
  }
});


